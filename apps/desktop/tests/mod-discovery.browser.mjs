function api(url, method) {
	requests.push(`${method} ${url.pathname}${url.search}`);
	const p = url.pathname;
	if (p === '/health') return { status: 'ok', apiVersion: '1.0.0' };
	if (p === '/system/memory') return { totalMib: 16384 };
	if (p === '/accounts') return [{ id: accountId, username: 'FixturePlayer', selected: true }];
	if (p === '/play-stats') return { schemaVersion: 1, accounts: {} };
	if (p === `/accounts/${accountId}/skin`) return { url: skinUrl, model: 'slim' };
	if (p === '/clients') return homeReadError ? { status: 503, error: 'fixture unavailable' } : homeEmpty ? [] : [client('first'), client('second'), client('vanilla')].filter(value => !deletedClients.has(value.name));
	if (p.endsWith('/launch-settings')) return { schemaVersion: 1, revision: 0, maxMemoryMib: 2048, initialMemoryMib: null, resolution: null };
	if (p === '/news') return { ...catalog, items: [1, 2, 3].map(number => ({ title: `Minecraft Java fixture ${number}`, url: `https://www.minecraft.net/article/fixture-${number}`, publishedAt: '2026-10-24T00:00:00Z', categories: ['Java'] })) };
	if (p === '/client-launches') return gameLaunch ? [gameLaunch] : [];
	if (p.endsWith('/launch') && method === 'POST') { gameLaunch = { id: 1, name: p.split('/')[2], phase: nextGamePhase, startedAt: nextGamePhase === 'running' ? Date.now() : null, cancelRequested: false, offlineTest: false, error: nextGamePhase === 'failed' ? 'fixture launch failed' : null, javaDownloadStarted: false }; return gameLaunch; }
	if (/^\/clients\/[^/]+$/.test(p)) {
		const name = p.split('/')[2];
		if (method === 'DELETE') {
			deletionSubmissions++;
			if (deletionMode === 'conflict') return { status: 409, error: 'fixture instance busy' };
			deletedClients.add(name);
			if (deletionMode === 'lost') return { status: 500, error: 'fixture reply lost' };
			return { id: `client-${name}`, removed: true, cleanupPending: false };
		}
		return name === 'missing' || deletedClients.has(name) ? { status: 404, error: 'not found' } : client(name);
	}
	if (p.endsWith('/resources')) { manifestReads++; return { schemaVersion: 4, revision: operation?.state === 'completed' ? 1 : 0, appliedRevision: 1, mods: operation?.state === 'completed' ? [{ filename: 'fabric-api.jar', sha256: 'a'.repeat(64), size: 100, enabled: true, source: 'modrinth', modrinthOrigin: { projectName: 'Installed fixture', direct: true } }] : [] }; }
	if (p === '/resources/curseforge/configuration') return { configured: false, issue: 'Offline fixture: API Key 未配置' };
	if (p === '/resources/modrinth/projects') { const index = Number(url.searchParams.get('index') ?? 0); return { ...catalog, items: projects.slice(index, index + 20), nextIndex: index === 0 ? 20 : null }; }
	if (/^\/resources\/modrinth\/projects\//.test(p)) return { ...catalog, project: projects.find(item => item.id === p.split('/').at(-1)) ?? projects[0] };
	if (p.endsWith('/files')) return { ...catalog, items: [file, ...Array.from({ length: 19 }, (_, i) => ({ ...file, id: `vers${String(i).padStart(4, '0')}`, displayName: `Fabric API 1.${i + 1}` }))], nextIndex: null };
	if (p.endsWith('/plan')) return { planId, expiresInMs: 600000, gameVersion: '26.3', revision: 0, totalBytes: 100, downloadBytes: 100, items: [{ project: projects[0], file, direct: true }], files: [{ projectId: 'abcdefgh', fileId: 'versiona', projectName: 'Fabric API', filename: file.fileName, size: 100, direct: true, reuse: false }], optionalProjects: ['optional'], warnings: [] };
	if (p.endsWith('/install')) {
		submissions++; const id = Number(p.split('/').at(-2));
		if (operation?.id !== id) { creations++; operation = { id, name: p.split('/')[2], state: 'running', cancelRequested: false, progress: { stage: 'downloading', completedFiles: 0, totalFiles: 1, downloadedBytes: 0, totalBytes: 100, receivedBytes: 0 }, revision: null, error: null }; }
		if (loseReply) { loseReply = false; return { status: 500, error: 'fixture response lost' }; }
		return operation;
	}
	if (p === '/resource-operations') return operation && !hideOperation ? [operation] : [];
	if (p === '/account-operations/active') return { operation: null };
	return [];
}
const server = createServer(async (req, res) => {
	try {
		const url = new URL(req.url, 'http://localhost');
		if (req.headers.authorization === 'Bearer fixture') {
			const value = api(url, req.method); res.writeHead(Number.isInteger(value.status) && value.status >= 400 ? value.status : 200, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }); res.end(JSON.stringify(value)); return;
		}
		const requested = path.resolve(build, `.${decodeURIComponent(url.pathname)}`);
		if (requested !== path.resolve(build) && !requested.startsWith(build)) { res.writeHead(403).end(); return; }
		let body, extension;
		try { body = await readFile(requested); extension = path.extname(requested); }
		catch { body = await readFile(path.join(build, 'index.html')); extension = '.html'; }
		res.writeHead(200, { 'Content-Type': ({ '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.svg': 'image/svg+xml' })[extension] ?? 'application/octet-stream' }); res.end(body);
	} catch { res.writeHead(500).end(); }
});
